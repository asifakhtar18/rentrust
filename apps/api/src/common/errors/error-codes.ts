/**
 * Canonical application error codes.
 *
 * Why: the API contract promises stable, machine-readable `error.code` values
 * that clients can branch on. Keeping them in one enum prevents drift and
 * accidental typos across modules.
 */
export enum ErrorCode {
  // Generic
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  BAD_REQUEST = 'BAD_REQUEST',
  UNAUTHORIZED = 'UNAUTHORIZED',
  FORBIDDEN = 'FORBIDDEN',
  NOT_FOUND = 'NOT_FOUND',
  CONFLICT = 'CONFLICT',
  RATE_LIMITED = 'RATE_LIMITED',
  INTERNAL_ERROR = 'INTERNAL_ERROR',

  // Auth
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  EMAIL_ALREADY_REGISTERED = 'EMAIL_ALREADY_REGISTERED',
  INVALID_TOKEN = 'INVALID_TOKEN',
  TOKEN_EXPIRED = 'TOKEN_EXPIRED',
  EMAIL_NOT_VERIFIED = 'EMAIL_NOT_VERIFIED',

  // Users
  USER_NOT_FOUND = 'USER_NOT_FOUND',

  // Properties
  PROPERTY_NOT_FOUND = 'PROPERTY_NOT_FOUND',
  PROPERTY_ALREADY_EXISTS = 'PROPERTY_ALREADY_EXISTS',

  // Localities
  LOCALITY_NOT_FOUND = 'LOCALITY_NOT_FOUND',

  // Reviews
  REVIEW_NOT_FOUND = 'REVIEW_NOT_FOUND',
  REVIEW_ALREADY_SUBMITTED = 'REVIEW_ALREADY_SUBMITTED',
  REVIEW_INVALID_STATE = 'REVIEW_INVALID_STATE',

  // Verification
  INVALID_VERIFICATION = 'INVALID_VERIFICATION',
  VERIFICATION_NOT_FOUND = 'VERIFICATION_NOT_FOUND',

  // Claims
  CLAIM_NOT_FOUND = 'CLAIM_NOT_FOUND',
  CLAIM_ALREADY_EXISTS = 'CLAIM_ALREADY_EXISTS',

  // Files
  INVALID_FILE_TYPE = 'INVALID_FILE_TYPE',
  FILE_TOO_LARGE = 'FILE_TOO_LARGE',
}
